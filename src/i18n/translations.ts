const translations = { en, "pt-BR": ptBR };

export function translate(
  language: Language,
  key: TranslationKey,
  params: Partial<Record<string, string | number>> = {},
): string {
  return translations[language][key].replace(/\{(\w+)\}/g, (placeholder: string, name: string) =>
    params[name] === undefined ? placeholder : String(params[name]),
  );
}
